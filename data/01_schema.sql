-- Extensión pgcrypto para generar hashes bcrypt compatibles con password_verify() de PHP en los seeds
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 1. ROLES
CREATE TABLE roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(150) NOT NULL
);

-- 2. USUARIOS
CREATE TABLE usuarios (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id         INTEGER NOT NULL REFERENCES roles(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    nombre         VARCHAR(80) NOT NULL,
    apellidos      VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    telefono       VARCHAR(25),
    direccion      VARCHAR(255),
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. MODELOS DE ZAPATILLAS
CREATE TABLE modelos (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku            VARCHAR(30) NOT NULL UNIQUE,
    marca          VARCHAR(60) NOT NULL,
    nombre         VARCHAR(120) NOT NULL,
    descripcion    TEXT NOT NULL,
    categoria      VARCHAR(50) NOT NULL 
                    CHECK (categoria IN ('lifestyle', 'running', 'basketball', 'skate')),
    precio_base    NUMERIC(10, 2) NOT NULL CHECK (precio_base >= 0),
    imagen_url     VARCHAR(255) NOT NULL,
    personalizable BOOLEAN NOT NULL DEFAULT FALSE,
    activo         BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. VARIANTES (TALLA, COLOR Y STOCK POR MODELO)
CREATE TABLE variantes_modelo (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo_id    INTEGER NOT NULL REFERENCES modelos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    talla        NUMERIC(4, 1) NOT NULL CHECK (talla BETWEEN 34.0 AND 50.0),
    color        VARCHAR(50) NOT NULL,
    stock        INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo INTEGER NOT NULL DEFAULT 3 CHECK (stock_minimo >= 0),
    UNIQUE (modelo_id, talla, color)
);

-- 5. PEDIDOS
CREATE TABLE pedidos (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_pedido    VARCHAR(30) NOT NULL UNIQUE,
    usuario_id       INTEGER NOT NULL REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    estado           VARCHAR(20) NOT NULL DEFAULT 'pendiente'
                     CHECK (estado IN ('pendiente', 'confirmado', 'preparacion', 'enviado', 'cancelado')),
    es_personalizado BOOLEAN NOT NULL DEFAULT FALSE,
    importe_total    NUMERIC(10, 2) NOT NULL DEFAULT 0.00 CHECK (importe_total >= 0),
    direccion_envio  VARCHAR(255) NOT NULL,
    notas            TEXT,
    creado_en        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 6. LÍNEAS DE PEDIDO
CREATE TABLE pedido_lineas (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id                INTEGER NOT NULL REFERENCES pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    variante_id              INTEGER NOT NULL REFERENCES variantes_modelo(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    cantidad                 INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario          NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal                 NUMERIC(10, 2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
    opciones_personalizacion JSONB DEFAULT NULL
);

-- 7. HISTORIAL DE TRANSICIONES DE ESTADO
CREATE TABLE pedido_historial_estados (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       INTEGER NOT NULL REFERENCES pedidos(id) ON UPDATE CASCADE ON DELETE CASCADE,
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20) NOT NULL
                    CHECK (estado_nuevo IN ('pendiente', 'confirmado', 'preparacion', 'enviado', 'cancelado')),
    usuario_id      INTEGER REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE SET NULL,
    comentario      VARCHAR(255),
    cambiado_en     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. AUDITORÍA DE EVENTOS DE NEGOCIO
CREATE TABLE auditoria_eventos (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  INTEGER REFERENCES usuarios(id) ON UPDATE CASCADE ON DELETE SET NULL,
    tipo_evento VARCHAR(50) NOT NULL,   -- ej: ALTA_PEDIDO, CANCELACION_PEDIDO, CAMBIO_ESTADO, AJUSTE_STOCK
    entidad     VARCHAR(50) NOT NULL,   -- ej: pedido, variante_modelo, usuario, modelo
    entidad_id  INTEGER,
    resultado   VARCHAR(20) NOT NULL CHECK (resultado IN ('OK', 'ERROR', 'DENEGADO')),
    detalles    JSONB DEFAULT '{}'::JSONB,
    ip_origen   VARCHAR(45),
    creado_en   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ÍNDICES PARA CONSULTAS FRECUENTES, FILTROS E INFORMES
CREATE INDEX idx_usuarios_rol ON usuarios(rol_id);
CREATE INDEX idx_modelos_categoria ON modelos(categoria);
CREATE INDEX idx_modelos_marca ON modelos(marca);
CREATE INDEX idx_variantes_modelo ON variantes_modelo(modelo_id);
CREATE INDEX idx_variantes_stock ON variantes_modelo(stock);
CREATE INDEX idx_pedidos_usuario ON pedidos(usuario_id);
CREATE INDEX idx_pedidos_estado ON pedidos(estado);
CREATE INDEX idx_pedido_lineas_pedido ON pedido_lineas(pedido_id);
CREATE INDEX idx_pedido_lineas_variante ON pedido_lineas(variante_id);
CREATE INDEX idx_historial_pedido ON pedido_historial_estados(pedido_id);
CREATE INDEX idx_auditoria_fecha ON auditoria_eventos(creado_en DESC);
CREATE INDEX idx_auditoria_entidad ON auditoria_eventos(entidad, entidad_id);